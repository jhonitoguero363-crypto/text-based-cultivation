export function resolveHerbIconName(name: string, level?: string): string | null {
  if (HERB_ICON_FILES[name]) return name
  const alias = HERB_ICON_ALIASES[name]
  if (alias && HERB_ICON_FILES[alias]) return alias
  if (level) {
    const fb = HERB_LEVEL_ICON_FALLBACK[level]
    if (fb && HERB_ICON_FILES[fb]) return fb
  }
  return null
}
